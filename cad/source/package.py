#!/usr/bin/env python3
"""Name the STEP solids, export each assembly solid on its own, write the guide and zip everything."""
import json
import os
import re
import shutil
import zipfile

import gmsh
import numpy as np

import rig
from rig import occ

OUT = 'out'
gmsh.initialize()
gmsh.option.setNumber('General.Terminal', 0)
gmsh.option.setNumber('General.Verbosity', 1)
rep = json.load(open(f'{OUT}/report.json'))
sl = json.load(open(f'{OUT}/slice_report.json'))


def rename(path, name):
    """Give the STEP product a readable name. Safe to run twice."""
    t = open(path).read()
    t, n = re.subn(r"PRODUCT\('[^']*',\s*'[^']*'", f"PRODUCT('{name}','{name}'", t, count=1)
    assert n == 1, (path, n)
    t = re.sub(r"FILE_NAME\('[^']*'", f"FILE_NAME('{name}'", t, count=1)
    open(path, 'w').write(t)
    return t


for name in rig.PRINTED:
    rename(f'{OUT}/step/{name}.step', name)

# every solid of the assembly as its own file, in its assembled position
os.makedirs(f'{OUT}/assembly/parts', exist_ok=True)
names = [n for n in list(rig.PRINTED) + list(rig.COPIES) + list(rig.BOUGHT) if n not in rig.ASM_ONLY]
facts = {}
for name in names:
    gmsh.model.add(name)
    dt = rig.build(name)
    occ.synchronize()
    keep = set(gmsh.model.getEntities(3))
    surf = gmsh.model.getBoundary(list(keep), combined=False, oriented=False, recursive=False)
    curv = gmsh.model.getBoundary(surf, combined=False, oriented=False, recursive=False)
    pts = gmsh.model.getBoundary(curv, combined=False, oriented=False, recursive=False) if curv else []
    ok = keep | set(surf) | set(curv) | set(pts)
    extra = [e for d in (2, 1, 0) for e in gmsh.model.getEntities(d) if e not in ok]
    if extra:
        occ.remove(extra)
        occ.synchronize()
    kind = 'printed' if name in rig.PRINTED or name in rig.COPIES else 'bought'
    path = f'{OUT}/assembly/parts/{kind}_{name}.step'
    gmsh.write(path)
    rename(path, name)
    facts[name] = (occ.getMass(3, dt[0][1]), occ.getCenterOfMass(3, dt[0][1]))
    gmsh.model.remove()

# name the bodies inside the combined assembly file by matching volume and centre
path = f'{OUT}/assembly/caustic_rig_assembly.step'
gmsh.model.add('asm')
dt = [d for d in occ.importShapes(path) if d[0] == 3]
occ.synchronize()
order = []
for _, t in dt:
    v, c = occ.getMass(3, t), np.array(occ.getCenterOfMass(3, t))
    best = min(facts, key=lambda n: abs(facts[n][0] - v) / facts[n][0] + np.linalg.norm(np.array(facts[n][1]) - c) / 100)
    order.append(best)
assert sorted(order) == sorted(names), (order, names)
text = open(path).read()
it = iter(order)
text, n = re.subn(r"MANIFOLD_SOLID_BREP\('[^']*'", lambda m: f"MANIFOLD_SOLID_BREP('{next(it)}'", text)
assert n == len(order)
pn = iter(['caustic_rig_assembly'] + order)        # the root product, then one product per solid in the same order


def prod(m):
    nm = next(pn)
    return f"PRODUCT('{nm}','{nm}'"


text, n = re.subn(r"PRODUCT\('[^']*',\s*'[^']*'", prod, text)
assert n == len(order) + 1, n
open(path, 'w').write(text)
gmsh.finalize()

# ---------------------------------------------------------------- guide
import mounts  # noqa: E402

QTY = {n: rig.QTY.get(n, 1) for n in rig.PRINTED}
rows = []
for n in rig.PRINTED:
    p, s = rep['parts'][n], sl[n]
    note = mounts.NOTE.get(n) or (mounts.CARD_NOTE if n.startswith('window_card') else mounts.ARM_NOTE)
    g = s['grams'] * QTY[n]
    rows.append(f"| `{n}` | {QTY[n]} | {p['size'][0]:.0f} x {p['size'][1]:.0f} x {p['size'][2]:.0f} | {'under 1 g' if g < 1 else format(g, '.0f') + ' g'} | {note} |")
total = sum(sl[n]['grams'] * QTY[n] for n in rig.PRINTED)
num = rep['numbers']
nl = chr(10)
step_text = nl.join(f"{i + 1}. **{s.split('. ', 1)[0]}.** {s.split('. ', 1)[1]}" for i, s in enumerate(mounts.steps(rig.ZB - rig.ZR, num['sled_x'][0])))
mount_rows = nl.join(f'| {a} | {b} | {c} | {d} |' for a, b, c, d in mounts.MOUNTS)
review_rows = nl.join(f'| {a} | {b} |' for a, b in mounts.REVIEW)
guide = f"""# Caustic bench rig: printable parts for a 2020 frame

Everything here was generated by one parametric script (`source/rig.py`) using the OpenCASCADE CAD kernel.
Units are millimetres. This is revision 2, after a part-by-part design review.

## What is in this folder

| Folder | Contents |
|---|---|
| `stl/` | {len(rig.PRINTED)} print-ready meshes, already turned to their print orientation and sitting on the bed. |
| `step/` | The same {len(rig.PRINTED)} parts as true solids (AP214 STEP), in the same orientation. SolidWorks, Fusion and Bambu Studio all open these. |
| `assembly/caustic_rig_assembly.step` | The whole rig as a STEP assembly of {len(order)} named parts: printed parts plus the bought parts as reference solids. |
| `assembly/parts/` | Every solid of the assembly as its own STEP file, already in its assembled position. |
| `source/` | The scripts. Change a number at the top of `rig.py`, then run `make.py`, `slice_check.py` and `package.py` in that order. They need Python with numpy and gmsh, plus PrusaSlicer and ADMesh for the checks. |
| `previews/` | Pictures of the assembly and of the main parts as they sit on the bed. |

## Printing on the P1S

Import the STEP files (smoother curves) or the STL files into Bambu Studio. Each part is already oriented. Do not rotate them.

* 0.4 mm nozzle, 0.2 mm layers, 3 walls, 15% infill.
* **No supports on any part.** Sideways holes are teardrop-shaped for this reason.
* Brim only on `hinge_bar`.
* Print the small parts first and check their fit before the stage.

| File | Qty | Size on the bed, mm | Filament | Notes |
|---|---|---|---|---|
{nl.join(rows)}

Total is about {total:.0f} g. Weights come from a test slice in PrusaSlicer with PETG density.

## Hardware used

{nl.join('* ' + h for h in mounts.HARDWARE)}

## How every part mounts

| Part | Goes on | Held by | Located by |
|---|---|---|---|
{mount_rows}

## Assembly

{step_text}

To change the LED-to-water distance, loosen the four side screws and slide the stage. To change the lean, loosen the sled and
slide it along the rails. To change the mirror tilt, hold the mirror, loosen the lock screw, move it and retighten.

## What the design review changed

| What was wrong | What it is now |
|---|---|
{review_rows}

## Still open

{nl.join('* ' + o for o in mounts.OPEN)}

## What I assumed about parts I could not measure

| Part | Assumed | If yours differs |
|---|---|---|
| Speaker | 40 mm rim, body under 37 mm across below the rim | It will sit higher in the seat. That still works. Trim the dipper riser to suit. |
| Speaker cone | Centre of the cone about 1 mm below the stage top | The dipper riser is printed 10 mm longer than needed for this. |
| Glass dish | 88 to 103 mm across, up to 20 mm tall | Tell me the size and I will regenerate the seat. |
| Mirror tile | 152.4 x 152.4 x 3 mm | The channel is 153.4 mm long and takes glass up to 3.4 mm thick with 1 mm tape. |
| Heatsink | 40 x 40 x 20 mm | The cradle is 40.6 mm wide. |
| LED star | Up to 24 mm across | |
| Extrusion | 2020 with 6 mm slots for M5 T-nuts | |

## How the files were checked

* {len(rep['checks'])} automatic checks pass.
* **Nothing overlaps.** No two parts occupy the same space, and the mirror clears everything at four tilts.
* **Every screw lines up.** A test shank the size of the screw passes through each hole and reaches the slot or thread it is meant for.
* **Every part is located.** Each part is nudged in each direction and has to run into the feature that is supposed to hold it.
* **Clearances are real.** Each sliding fit is nudged by its design clearance and has to stay free.
* **The beam fits the mirror** for every window card at every tilt.
* Each STL was re-read by PrusaSlicer and ADMesh: all are manifold, single-part, with no repairs needed.
* Each part was test-sliced with automatic supports switched on. The slicer placed no support on any part.
* Each STEP file was read back and has one solid with the same volume as the model.

## SolidWorks

Open any `.step` file with File > Open. Each part arrives as a solid body with no feature history. I cannot write native
`.SLDPRT` files, because that format needs SolidWorks itself. For the whole rig, open `assembly/caustic_rig_assembly.step`:
it is a STEP assembly of {len(order)} named parts, already in position. The files in `assembly/parts/` are the same solids one per file.
"""
open(f'{OUT}/README.md', 'w').write(guide)

os.makedirs(f'{OUT}/source', exist_ok=True)
for f in ('rig.py', 'make.py', 'slice_check.py', 'package.py', 'mounts.py'):
    shutil.copy(f, f'{OUT}/source/{f}')
os.makedirs(f'{OUT}/previews', exist_ok=True)
for src, dst in (('parts_sheet.png', 'parts_on_the_bed.png'), ('../v4_out.png', 'assembly_front.png'), ('../v4_back.png', 'assembly_back.png'), ('../v4_sec.png', 'assembly_section.png')):
    if os.path.exists(src):
        shutil.copy(src, f'{OUT}/previews/{dst}')

ZIP = '../caustic-bench-rig-cad.zip'
with zipfile.ZipFile(ZIP, 'w', zipfile.ZIP_DEFLATED, compresslevel=9) as z:
    for root, _, files in os.walk(OUT):
        for f in sorted(files):
            if f.endswith(('.npz', '.json')):
                continue
            p = os.path.join(root, f)
            z.write(p, os.path.join('caustic-bench-rig-cad', os.path.relpath(p, OUT)))
print('zip', round(os.path.getsize(ZIP) / 1e6, 2), 'MB;', len(zipfile.ZipFile(ZIP).namelist()), 'files')
print('assembly bodies:', order)
